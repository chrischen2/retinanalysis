"""retinanalysis — lazy top-level package.

Public names (functions, classes, submodules, path constants) are resolved
on first access via PEP 562 ``__getattr__`` instead of being imported all at
once. This keeps ``import retinanalysis`` fast (~0.1 s instead of ~3.5 s) so
Jupyter kernel restarts feel instant: DataJoint, matplotlib, scipy and xarray
are pulled in only when you actually call something that needs them.

Behaviour is identical to the old eager import:

* ``import retinanalysis as ra; ra.analyze_experiment(...)`` works the same.
* ``from retinanalysis import DATA_DIR`` works (resolved via ``__getattr__``).
* Every name the old eager ``__init__`` exposed is still resolvable. Names
  that only ever existed because an old ``from .x import *`` leaked them
  (typing aliases, ``np``/``pd``, the unused schema-table placeholders, ...)
  are recovered by ``_STAR_MODULES`` fallback below.

The two registries are generated by introspecting the eager package; see
``tests/test_lazy_import.py`` which asserts name-for-name parity and that the
common offline workflow does not import DataJoint.

NOTE on DataJoint: the old ``config.schema`` was imported first and opened the
DB connection at ``import`` time. Now ``schema`` (and the connection) load on
first access to anything DataJoint-backed. Every consumer of the schema tables
imports ``retinanalysis.config.schema`` directly, so the tables are always
declared before use — the old "must be first" ordering is preserved naturally.
"""
